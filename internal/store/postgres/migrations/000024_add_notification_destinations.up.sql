-- Notification destinations (RFC 0006 unit D1). A rule's email recipients and
-- webhook URLs become reusable destinations linked to the rule, and the two
-- JSON columns on alerts are dropped.

CREATE TABLE notification_destinations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 TEXT NOT NULL,
    type                 TEXT NOT NULL CHECK (type IN ('email', 'webhook', 'slack', 'pagerduty')),
    scope                TEXT NOT NULL CHECK (scope IN ('private', 'team', 'global')),
    team_id              BIGINT REFERENCES teams(id) ON DELETE CASCADE,
    config_json          TEXT NOT NULL DEFAULT '{}',
    secret               TEXT NOT NULL DEFAULT '',
    is_active            BOOLEAN NOT NULL DEFAULT TRUE,
    created_by           BIGINT REFERENCES users(id) ON DELETE SET NULL,
    last_delivery_at     TIMESTAMPTZ,
    last_delivery_status TEXT,
    last_delivery_error  TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((scope = 'team') = (team_id IS NOT NULL))
);

CREATE INDEX idx_notification_destinations_team ON notification_destinations(team_id);
CREATE INDEX idx_notification_destinations_created_by ON notification_destinations(created_by);

CREATE TABLE alert_destinations (
    alert_id       BIGINT NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
    destination_id BIGINT NOT NULL REFERENCES notification_destinations(id) ON DELETE RESTRICT,
    PRIMARY KEY (alert_id, destination_id)
);

CREATE INDEX idx_alert_destinations_destination ON alert_destinations(destination_id);

-- The targets as arrays; anything that is not a JSON array reads as none.
CREATE TEMP TABLE migrated_targets AS
SELECT
    a.id AS alert_id, a.name, a.created_by,
    CASE WHEN a.webhook_urls_json ~ '^\s*\[' THEN a.webhook_urls_json::jsonb ELSE '[]'::jsonb END AS webhooks,
    CASE WHEN a.recipient_user_ids_json ~ '^\s*\[' THEN a.recipient_user_ids_json::jsonb ELSE '[]'::jsonb END AS recipients
FROM alerts a;

CREATE TEMP TABLE migrated_webhooks AS
SELECT DISTINCT t.alert_id, t.created_by, btrim(u.value #>> '{}') AS url
FROM migrated_targets t, jsonb_array_elements(t.webhooks) u
WHERE jsonb_typeof(u.value) = 'string' AND btrim(u.value #>> '{}') <> '';

-- Each distinct webhook URL of one creator becomes one private version 1
-- webhook destination named after the URL's host. The name never carries a
-- byte of the userinfo: the authority ends at the first '/', '?' or '#', and
-- the userinfo ends at its last '@'. An '@' after the authority means the
-- userinfo held one of those delimiters, so the authority is unclear and the
-- name has no host. An unparsable host also leaves the plain name.
INSERT INTO notification_destinations (name, type, scope, config_json, secret, created_by)
SELECT
    CASE WHEN host = '' THEN 'Webhook' ELSE 'Webhook ' || host END,
    'webhook', 'private', '{"payload_version":1}', url, created_by
FROM (
    SELECT created_by, url,
        CASE
            WHEN after_authority LIKE '%@%' THEN ''
            WHEN hostport LIKE '[%' THEN COALESCE(substring(hostport from '^(\[[^\]]*\])'), '')
            ELSE split_part(hostport, ':', 1)
        END AS host
    FROM (
        SELECT created_by, url,
            substring(rest from '^[^/?#]*(.*)$') AS after_authority,
            regexp_replace(substring(rest from '^([^/?#]*)'), '^.*@', '') AS hostport
        FROM (
            SELECT DISTINCT created_by, url,
                COALESCE(substring(url from '^[A-Za-z][A-Za-z0-9+.-]*://(.*)$'), url) AS rest
            FROM migrated_webhooks
        ) r
    ) a
) w
ORDER BY created_by, url;

INSERT INTO alert_destinations (alert_id, destination_id)
SELECT DISTINCT w.alert_id, d.id
FROM migrated_webhooks w
JOIN notification_destinations d
    ON d.type = 'webhook' AND d.secret = w.url AND d.created_by IS NOT DISTINCT FROM w.created_by;

-- Each rule with recipients gets one private email destination with the
-- same user ids. Its id is the highest destination id so far plus the rule
-- id, which links it to the rule without a lookup by name.
CREATE TEMP TABLE migrated_recipients AS
SELECT DISTINCT t.alert_id, (u.value #>> '{}')::bigint AS user_id
FROM migrated_targets t, jsonb_array_elements(t.recipients) u
WHERE jsonb_typeof(u.value) = 'number' AND (u.value #>> '{}') ~ '^[0-9]+$';

CREATE TEMP TABLE migrated_email_base AS
SELECT COALESCE(MAX(id), 0) AS base FROM notification_destinations;

INSERT INTO notification_destinations (id, name, type, scope, config_json, created_by)
SELECT
    b.base + t.alert_id,
    'Email for ' || t.name,
    'email', 'private',
    jsonb_build_object('user_ids', (SELECT jsonb_agg(r.user_id ORDER BY r.user_id) FROM migrated_recipients r WHERE r.alert_id = t.alert_id))::text,
    t.created_by
FROM migrated_targets t, migrated_email_base b
WHERE t.alert_id IN (SELECT alert_id FROM migrated_recipients)
ORDER BY t.alert_id;

INSERT INTO alert_destinations (alert_id, destination_id)
SELECT DISTINCT r.alert_id, b.base + r.alert_id
FROM migrated_recipients r, migrated_email_base b;

-- Explicit ids above do not move the identity sequence.
SELECT setval(pg_get_serial_sequence('notification_destinations', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL)
FROM notification_destinations;

DROP TABLE migrated_recipients;
DROP TABLE migrated_email_base;
DROP TABLE migrated_webhooks;
DROP TABLE migrated_targets;

ALTER TABLE alerts DROP COLUMN recipient_user_ids_json;
ALTER TABLE alerts DROP COLUMN webhook_urls_json;
